"""PostgreSQL: пул соединений и схема. Все времена хранятся в UTC (TIMESTAMPTZ)."""
import os
from pathlib import Path

from dotenv import dotenv_values
from psycopg.rows import dict_row
from psycopg_pool import ConnectionPool

config = dotenv_values(Path(__file__).resolve().parent / ".env", interpolate=False)


# Переменные окружения имеют приоритет над файлом .env.
def database_url():
    value = (os.environ.get("DATABASE_URL") or config.get("DATABASE_URL") or "").strip()
    if not value:
        raise RuntimeError("Не задан DATABASE_URL")
    return value


CONNECTION_KWARGS = {"row_factory": dict_row, "options": "-c TimeZone=UTC"}

# Единый снимок для чтения нескольких запросов (аналог BEGIN в SQLite).
SNAPSHOT = "SET TRANSACTION ISOLATION LEVEL REPEATABLE READ READ ONLY"

pool = None


def open_pool():
    global pool
    pool = ConnectionPool(database_url(), min_size=1, max_size=10, kwargs=CONNECTION_KWARGS, open=False)
    pool.open(wait=True, timeout=30)


def close_pool():
    pool.close()


# Коммит при выходе из with, откат при исключении (в том числе HTTPException).
def connect_db():
    return pool.connection()


SCHEMA = """
CREATE TABLE IF NOT EXISTS job_descriptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    direction TEXT NOT NULL,
    content TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'draft',
    version INTEGER NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    approved_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS vacancies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    direction TEXT NOT NULL,
    description TEXT NOT NULL,
    criteria JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    vacancy_status TEXT NOT NULL DEFAULT 'active' CHECK (vacancy_status IN ('active', 'archived')),
    archived_at TIMESTAMPTZ,
    archive_version INTEGER NOT NULL DEFAULT 1,
    language TEXT,
    source_jd_id BIGINT REFERENCES job_descriptions(id),
    source_jd_version INTEGER,
    preferred_criteria JSONB NOT NULL DEFAULT '[]'
);

CREATE UNIQUE INDEX IF NOT EXISTS vacancy_jd_version
    ON vacancies(source_jd_id, source_jd_version)
    WHERE source_jd_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vacancy_id BIGINT NOT NULL REFERENCES vacancies(id),
    name TEXT NOT NULL,
    contact TEXT NOT NULL,
    source TEXT NOT NULL,
    resume_text TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'new',
    created_at TIMESTAMPTZ NOT NULL,
    review_version INTEGER NOT NULL DEFAULT 1
);

CREATE INDEX IF NOT EXISTS applications_stage ON applications(status);
CREATE INDEX IF NOT EXISTS applications_vacancy ON applications(vacancy_id);
CREATE INDEX IF NOT EXISTS applications_created ON applications(created_at);

CREATE TABLE IF NOT EXISTS application_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT NOT NULL REFERENCES applications(id),
    event_type TEXT NOT NULL CHECK (event_type IN ('stage', 'note')),
    old_status TEXT,
    new_status TEXT,
    note TEXT,
    request_id TEXT,
    created_at TIMESTAMPTZ NOT NULL,
    UNIQUE (application_id, request_id)
);

CREATE INDEX IF NOT EXISTS application_events_app ON application_events(application_id, id);

CREATE TABLE IF NOT EXISTS candidate_assessments (
    application_id BIGINT PRIMARY KEY REFERENCES applications(id),
    criteria_json JSONB NOT NULL,
    answers_json JSONB NOT NULL,
    version INTEGER NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS candidate_tasks (
    application_id BIGINT PRIMARY KEY REFERENCES applications(id),
    title TEXT NOT NULL,
    comment TEXT NOT NULL,
    due_at TIMESTAMPTZ NOT NULL,
    completed_at TIMESTAMPTZ,
    version INTEGER NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS candidate_task_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT NOT NULL REFERENCES applications(id),
    action TEXT NOT NULL,
    snapshot JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX IF NOT EXISTS candidate_task_events_app ON candidate_task_events(application_id, id);

CREATE TABLE IF NOT EXISTS company_settings (
    id INTEGER PRIMARY KEY CHECK (id = 1),
    data JSONB NOT NULL,
    version INTEGER NOT NULL DEFAULT 1,
    updated_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS report_delivery (
    recipient BIGINT NOT NULL,
    period TEXT NOT NULL,
    status TEXT NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (recipient, period)
);

-- Additive migration for JD templates and recruiter-triggered AI review.
ALTER TABLE job_descriptions ADD COLUMN IF NOT EXISTS internal_notes TEXT NOT NULL DEFAULT '';
ALTER TABLE job_descriptions ADD COLUMN IF NOT EXISTS template_inputs JSONB NOT NULL DEFAULT '{}';
CREATE TABLE IF NOT EXISTS candidate_ai_runs (
    request_id TEXT PRIMARY KEY,
    application_id BIGINT NOT NULL REFERENCES applications(id),
    fingerprint TEXT NOT NULL,
    status TEXT NOT NULL CHECK (status IN ('running','completed','failed','unknown')),
    started DOUBLE PRECISION NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    model TEXT NOT NULL,
    result_json JSONB,
    detail TEXT NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS candidate_ai_app ON candidate_ai_runs(application_id,started);
CREATE UNIQUE INDEX IF NOT EXISTS candidate_ai_running ON candidate_ai_runs(application_id) WHERE status='running';
"""

# Произвольный ключ: api и bot могут стартовать одновременно.
SCHEMA_LOCK = 4_826_113


def init_db(connection):
    connection.execute("SELECT pg_advisory_xact_lock(%s)", (SCHEMA_LOCK,))
    connection.execute(SCHEMA)
